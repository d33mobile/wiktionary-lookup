import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { entries, scriptOf } from '../sources/wiktionary.js';
import { buildIndex } from '../build-index.js';
import { serializeIndex, deserializeIndexWithHeader } from '../lib/index-format.js';
import { openIndex, DEFAULT_LANGUAGE } from '../lib/engine.js';
import { entries as cedictEntries } from '../sources/cedict-text.js';
import { FIXTURE as CEDICT_FIXTURE } from './helpers.js';

// Records of the kaikki.org extracts of five languages, reduced to the fields
// the source reads (test/fixtures/wiktionary-<code>.jsonl, regenerated by
// make-wiktionary-generic-fixture.js).
const fixture = (code) => resolve(dirname(fileURLToPath(import.meta.url)), 'fixtures', `wiktionary-${code}.jsonl`);

async function load(code) {
  const info = {};
  const rows = [];
  for await (const e of entries(fixture(code), info)) rows.push(e);
  return { rows, info };
}

async function open(code) {
  const info = {};
  const sections = await buildIndex(entries(fixture(code), info), info);
  return openIndex(serializeIndex(sections, info));
}

const heads = (rows) => rows.map((r) => r.simp);

describe('generic Wiktionary source', () => {
  test('language metadata from the records', async () => {
    const expected = {
      en: { code: 'en', name: 'English', script: 'Latn', hasRomanization: false },
      de: { code: 'de', name: 'German', script: 'Latn', hasRomanization: false },
      ja: { code: 'ja', name: 'Japanese', script: 'Jpan', hasRomanization: true },
      ru: { code: 'ru', name: 'Russian', script: 'Cyrl', hasRomanization: true },
      pl: { code: 'pl', name: 'Polish', script: 'Latn', hasRomanization: false },
    };
    for (const [code, language] of Object.entries(expected)) {
      const { info } = await load(code);
      assert.deepEqual(info.language, language, code);
      assert.deepEqual(info.keys, { headword: 'fold', romanization: 'fold' });
    }
  });

  test('Japanese: kana reading from the furigana, romaji as romanization', async () => {
    const { rows } = await load('ja');
    const find = (simp, pinyin) => rows.find((r) => r.simp === simp && r.pinyin === pinyin);
    assert.equal(find('東京', 'Tōkyō').trad, 'とうきょう');
    assert.equal(find('食べる', 'taberu').trad, 'たべる');
    assert.equal(find('猫', 'neko').trad, 'ねこ');
    assert.match(find('猫', 'neko').definition, /^\(noun\) a cat/);
    assert.equal(find('猫', '').definition, '(character) cat', 'the kanji record has no reading of its own');
  });

  test('Russian: transliteration, stressed canonical form as alternative', async () => {
    const { rows } = await load('ru');
    const moskva = rows.find((r) => r.simp === 'Москва');
    assert.deepEqual([moskva.trad, moskva.pinyin], ['Москва́', 'Moskvá']);
    assert.deepEqual(rows.filter((r) => r.simp === 'дома').map((r) => r.trad), ['до́ма', 'дома́'], 'one entry per stress');
  });

  test('Latin-script languages get no romanization, records of a title merge', async () => {
    for (const code of ['en', 'de', 'pl']) {
      const { rows } = await load(code);
      assert.ok(rows.every((r) => r.pinyin === ''), code);
      assert.equal(new Set(rows.map((r) => `${r.simp}\t${r.trad}`)).size, rows.length, code);
    }
    const { rows } = await load('de');
    const haus = rows.find((r) => r.simp === 'Haus');
    assert.match(haus.definition, /^\(noun\) house, building\/.*\/\(name\) /);
  });

  test('script of a title', () => {
    assert.deepEqual(['dom', 'дом', 'σπίτι', 'كتاب', '猫', 'ねこ', '고양이', '123'].map(scriptOf),
      ['Latn', 'Cyrl', 'Grek', 'Arab', 'Hani', 'Hira', 'Hang', null]);
  });
});

describe('search on generic indexes (headword > form / romanization > definition)', async () => {
  const idx = Object.fromEntries(await Promise.all(['en', 'de', 'ja', 'ru', 'pl'].map(async (c) => [c, await open(c)])));

  test('the header carries language and keys', () => {
    assert.deepEqual(idx.ru.language, { code: 'ru', name: 'Russian', script: 'Cyrl', hasRomanization: true });
    assert.equal(idx.ru.keyFns.scheme.headword, 'fold');
    assert.equal(idx.de.keys.pinyinBare, null, 'no romanization key without romanizations');
    assert.equal(idx.ru.keys.pinyinToned, null, 'one romanization key in the fold scheme');
  });

  test('headwords are case and diacritic insensitive', () => {
    assert.equal(idx.de.search('haus')[0].simp, 'Haus');
    assert.equal(idx.de.search('hauser')[0].simp, 'Häuser');
    assert.equal(idx.de.search('straße')[0].simp, 'Straße');
    assert.equal(idx.en.search('cafe')[0].simp, 'café');
    assert.equal(idx.en.search('new york')[0].simp, 'New York');
    assert.equal(idx.pl.search('zolw')[0].simp, 'żółw');
    assert.deepEqual(new Set(heads(idx.pl.search('lodz'))), new Set(['łódź', 'Łódź']));
    assert.equal(idx.ru.search('москва')[0].simp, 'Москва');
    assert.equal(idx.ru.search('еж')[0].simp, 'ёж');
    assert.equal(idx.ru.search('чаи')[0].simp, 'чай');
  });

  test('exact headword before prefix, English after the headword', () => {
    const rows = idx.de.search('haus', { limit: 50 });
    assert.deepEqual(heads(rows.slice(0, 2)), ['Haus', 'Häuser']);
    assert.deepEqual(rows.map((r) => r.matchedOn).slice(0, 2), ['simp', 'simp']);
    const tee = idx.en.search('tee');
    assert.equal(tee[0].simp, 'tee', 'the English headword before glosses');
  });

  test('romanization and kana reading find the native spelling', () => {
    assert.equal(idx.ja.search('neko')[0].simp, '猫');
    assert.equal(idx.ja.search('neko')[0].matchedOn, 'pinyinBare');
    assert.equal(idx.ja.search('tokyo')[0].simp, '東京');
    assert.equal(idx.ja.search('taberu')[0].simp, '食べる');
    const kana = idx.ja.search('ねこ', { limit: 50 });
    assert.deepEqual(new Set(heads(kana.slice(0, 2))), new Set(['猫', 'ネコ']));
    assert.equal(kana[0].matchedOn, 'trad');
    assert.equal(idx.ja.search('猫')[0].matchedOn, 'simp');
    assert.equal(idx.ru.search('moskva')[0].simp, 'Москва');
    assert.equal(idx.ru.search('dom')[0].simp, 'дом');
  });

  test('English glosses find the word', () => {
    assert.equal(idx.de.search('house')[0].simp, 'Haus');
    assert.equal(idx.de.search('tea')[0].simp, 'Tee');
    assert.equal(idx.ru.search('tea')[0].simp, 'чай');
    assert.equal(idx.pl.search('tea')[0].simp, 'herbata');
    assert.equal(idx.ja.search('cat')[0].simp, '猫');
    assert.deepEqual(heads(idx.de.search('/haus')), ['Häuser'], 'English only with "/"');
  });

  test('typing narrows and matches a fresh session', () => {
    const seqs = [[idx.pl, ['z', 'zo', 'zol', 'zolw', 'zol']], [idx.ru, ['m', 'mo', 'mosk', 'moskva', 'м', 'мо', 'моск']],
      [idx.ja, ['n', 'ne', 'neko', 'ね', 'ねこ', '猫']], [idx.de, ['h', 'ha', 'hau', 'haus', 'hause', 'house']]];
    for (const [d, seq] of seqs) {
      const session = d.newSession();
      for (const q of seq) {
        assert.deepEqual(heads(session.search(q, { limit: 50 })), heads(d.newSession().search(q, { limit: 50 })), `${seq} at ${q}`);
      }
    }
    for (const [d, seq] of [[idx.de, ['h', 'ha', 'hau', 'haus']], [idx.ru, ['м', 'мо', 'моск']], [idx.ja, ['n', 'ne', 'nek', 'neko']]]) {
      const session = d.newSession();
      for (const q of seq) session.search(q);
      session.search(seq[seq.length - 2]);
      assert.equal(session.lastStats.bisects, 0, `backspace after ${seq.at(-1)} reuses the stored ranges`);
    }
  });
});

test('an index without language metadata loads as Chinese', async () => {
  const bytes = serializeIndex(await buildIndex(cedictEntries(CEDICT_FIXTURE)));
  const { header } = deserializeIndexWithHeader(bytes);
  assert.equal(header.language, undefined);
  const d = openIndex(bytes);
  assert.deepEqual(d.language, DEFAULT_LANGUAGE);
  assert.equal(d.source, null);
  assert.equal(d.search('nihao')[0].simp, '你好');
});
